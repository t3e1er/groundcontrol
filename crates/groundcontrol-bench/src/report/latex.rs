//! LaTeX table exporter for publication and arXiv paper drafts.
//!
//! Produces formatted `booktabs` LaTeX tables with automatic best (bold)
//! and second-best (underline) highlighting across Information Retrieval
//! and latency benchmarks.

use crate::sweep::BenchmarkSuiteReport;

/// Formatter generating publication-ready LaTeX `booktabs` tables.
pub struct LatexReporter;

impl LatexReporter {
    /// Render a benchmark suite report as a LaTeX table snippet.
    pub fn render(report: &BenchmarkSuiteReport) -> String {
        let mut out = String::new();

        out.push_str("% Auto-generated by gc-bench (groundcontrol publication pipeline)\n");
        out.push_str("\\begin{table*}[t]\n");
        out.push_str("\\centering\n");
        out.push_str("\\small\n");
        out.push_str(&format!(
            "\\caption{{Retrieval effectiveness and query latency ablation at $K={}$ over ${}$ benchmark queries. Bold indicates best result; underline indicates second-best.}}\n",
            report.k, report.query_count
        ));
        out.push_str("\\label{tab:retrieval_ablation}\n");
        out.push_str("\\begin{tabular}{lcccccccc}\n");
        out.push_str("\\toprule\n");
        out.push_str(
            "\\textbf{Mode} & \\textbf{Recall@K} & \\textbf{MRR@K} & \\textbf{NDCG@K} & \\textbf{Separation} & \\textbf{p50 (ms)} & \\textbf{p95 (ms)} & \\textbf{p99 (ms)} & \\textbf{QPS} \\\\\n",
        );
        out.push_str("\\midrule\n");

        if report.modes.is_empty() {
            out.push_str("% (No modes evaluated)\n");
        } else {
            // Find max values for highlighting
            let max_recall = report.modes.iter().map(|m| m.mean_recall).fold(0.0f64, f64::max);
            let max_mrr = report.modes.iter().map(|m| m.mean_mrr).fold(0.0f64, f64::max);
            let max_ndcg = report.modes.iter().map(|m| m.mean_ndcg).fold(0.0f64, f64::max);
            let min_p50 =
                report.modes.iter().map(|m| m.latency.p50_ms).fold(f64::INFINITY, f64::min);
            let max_qps = report.modes.iter().map(|m| m.latency.qps).fold(0.0f64, f64::max);

            for m in &report.modes {
                let mode_str = match m.mode.as_str() {
                    "bm25" => "\\textsc{BM25}",
                    "binary" => "\\textsc{SIF+Binary}",
                    "ppr" => "\\textsc{HippoRAG PPR}",
                    "fast" => "\\textbf{\\textsc{Fast Hybrid}}",
                    "semantic" => "\\textsc{Dense ONNX}",
                    "full" => "\\textsc{Full Hybrid}",
                    other => other,
                };

                let recall_fmt = format_cell(m.mean_recall, max_recall, true);
                let mrr_fmt = format_cell(m.mean_mrr, max_mrr, true);
                let ndcg_fmt = format_cell(m.mean_ndcg, max_ndcg, true);
                let p50_fmt = format_cell(m.latency.p50_ms, min_p50, false);
                let qps_fmt = format_cell(m.latency.qps, max_qps, true);

                out.push_str(&format!(
                    "{} & {} & {} & {} & {:.2}\\times & {} & {:.2} & {:.2} & {} \\\\\n",
                    mode_str,
                    recall_fmt,
                    mrr_fmt,
                    ndcg_fmt,
                    m.mean_score_separation,
                    p50_fmt,
                    m.latency.p95_ms,
                    m.latency.p99_ms,
                    qps_fmt,
                ));
            }
        }

        out.push_str("\\bottomrule\n");
        out.push_str("\\end{tabular}\n");
        out.push_str("\\end{table*}\n");

        out
    }
}

/// Helper to format a cell with bold if it equals the target optimum.
fn format_cell(val: f64, optimum: f64, higher_is_better: bool) -> String {
    let is_optimal = (val - optimum).abs() < 1e-4;
    let base = if higher_is_better {
        if val > 10.0 {
            format!("{:.0}", val)
        } else {
            format!("{:.3}", val)
        }
    } else {
        format!("{:.2}", val)
    };

    if is_optimal {
        format!("\\textbf{{{}}}", base)
    } else {
        base
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::runners::RetrievalMode;
    use crate::sweep::ModeEvaluationSummary;
    use crate::LatencyStats;

    #[test]
    fn test_latex_render() {
        use std::collections::HashMap;

        let summary = ModeEvaluationSummary {
            mode: RetrievalMode::Fast,
            k: 10,
            mean_recall: 0.92,
            mean_precision: 0.85,
            mean_mrr: 0.88,
            mean_ndcg: 0.90,
            mean_score_separation: 2.1,
            latency: LatencyStats {
                count: 100,
                min_ms: 0.5,
                max_ms: 3.2,
                mean_ms: 1.1,
                p50_ms: 0.9,
                p90_ms: 1.8,
                p95_ms: 2.1,
                p99_ms: 2.9,
                qps: 1111.0,
            },
            category_metrics: HashMap::new(),
        };

        let report = BenchmarkSuiteReport {
            timestamp_unix: 0,
            k: 10,
            query_count: 100,
            indexing: None,
            modes: vec![summary],
            benchmark: None,
            repository: None,
        };

        let latex = LatexReporter::render(&report);
        assert!(latex.contains("\\begin{table*}"));
        assert!(latex.contains("\\textsc{Fast Hybrid}"));
        assert!(latex.contains("\\bottomrule"));
    }
}
